<?php
declare(strict_types=1);

namespace App\Core;

/** Loads config/config.php (written by the installer). Holds no secrets in source control. */
final class Config
{
    private static ?array $data = null;

    public static function path(): string
    {
        return MOTO_ROOT . '/config/config.php';
    }

    public static function exists(): bool
    {
        return is_file(self::path());
    }

    public static function load(?array $override = null): void
    {
        if ($override !== null) {
            self::$data = $override;
            return;
        }
        if (!self::exists()) {
            self::$data = [];
            return;
        }
        $data = require self::path();
        self::$data = is_array($data) ? $data : [];
    }

    /** Dot-notation lookup, e.g. Config::get('db.host'). */
    public static function get(string $key, mixed $default = null): mixed
    {
        if (self::$data === null) {
            self::load();
        }
        $value = self::$data;
        foreach (explode('.', $key) as $part) {
            if (!is_array($value) || !array_key_exists($part, $value)) {
                return $default;
            }
            $value = $value[$part];
        }
        return $value;
    }

    /** Render a config array as a PHP file that returns it. */
    public static function export(array $config): string
    {
        return "<?php\n"
            . "// MotoSupply POS configuration. Generated by the installer.\n"
            . "// Contains secrets: never commit this file or make it web-accessible.\n"
            . "defined('MOTO_ROOT') || exit;\n\n"
            . 'return ' . var_export($config, true) . ";\n";
    }
}
