<?php
declare(strict_types=1);

namespace App\Core;

/** Loads config/config.php (written by the installer). Holds no secrets in source control. */
final class Config
{
    private static ?array $data = null;

    public static function path(): string
    {
        return MOTO_ROOT . '/config/config.php';
    }

    public static function exists(): bool
    {
        return is_file(self::path());
    }

    public static function load(?array $override = null): void
    {
        if ($override !== null) {
            self::$data = $override;
            return;
        }
        if (!self::exists()) {
            self::$data = [];
            return;
        }
        $data = require self::path();
        self::$data = is_array($data) ? $data : [];
    }

    /** Dot-notation lookup, e.g. Config::get('db.host'). */
    public static function get(string $key, mixed $default = null): mixed
    {
        if (self::$data === null) {
            self::load();
        }
        $value = self::$data;
        foreach (explode('.', $key) as $part) {
            if (!is_array($value) || !array_key_exists($part, $value)) {
                return $default;
            }
            $value = $value[$part];
        }
        return $value;
    }

    /** Render a config array as a PHP file that returns it. */
    public static function export(array $config): string
    {
        return "<?php\n"
            . "// MotoSupply POS configuration. Generated by the installer.\n"
            . "// Contains secrets: never share this file or make it web-accessible.\n"
            . "defined('MOTO_ROOT') || exit;\n\n"
            . 'return ' . var_export($config, true) . ";\n";
    }

    /**
     * A writable folder OUTSIDE the public document root (e.g. next to htdocs/public_html),
     * or null when the host does not allow it. Used to keep secrets out of the web folder.
     */
    public static function privateDir(): ?string
    {
        $docRoot = (string) ($_SERVER['DOCUMENT_ROOT'] ?? '');
        $docReal = $docRoot !== '' ? @realpath($docRoot) : false;
        $appReal = @realpath(MOTO_ROOT);
        if ($docReal === false || $appReal === false) {
            return null;
        }
        $docReal = rtrim(str_replace('\\', '/', $docReal), '/');
        $appReal = str_replace('\\', '/', $appReal);
        if (!str_starts_with($appReal . '/', $docReal . '/')) {
            return null;
        }
        $parent = dirname($docReal);
        if ($parent === $docReal || $parent === '/' || $parent === '.') {
            return null;
        }
        $dir = $parent . '/motosupply-private';
        try {
            if (!@is_dir($dir) && !@mkdir($dir, 0700)) {
                return null;
            }
            if (!@is_writable($dir)) {
                return null;
            }
        } catch (\Throwable) {
            return null; // open_basedir restrictions
        }
        return $dir;
    }

    /** Relative path from directory $from to file $to (both absolute). */
    public static function relativePath(string $from, string $to): string
    {
        $f = explode('/', trim(str_replace('\\', '/', $from), '/'));
        $t = explode('/', trim(str_replace('\\', '/', $to), '/'));
        while ($f && $t && $f[0] === $t[0]) {
            array_shift($f);
            array_shift($t);
        }
        return str_repeat('../', count($f)) . implode('/', $t);
    }

    /**
     * Save the configuration. Prefers a private folder outside the document root and leaves
     * only a small pointer file in config/; otherwise writes config/config.php (web-denied).
     * Writes are atomic (temp file + rename). Returns 'private' or 'webroot'.
     */
    public static function write(array $config): string
    {
        $content = self::export($config);
        $private = self::privateDir();
        if ($private !== null) {
            $realRoot = str_replace('\\', '/', (string) realpath(MOTO_ROOT));
            $file = $private . '/config-' . substr(hash('sha256', $realRoot), 0, 12) . '.php';
            @file_put_contents($private . '/.htaccess', "Require all denied\n");
            @file_put_contents($private . '/index.html', '');
            if (self::atomicWrite($file, $content)) {
                $rel = self::relativePath($realRoot . '/config', $file);
                $stub = "<?php\n// MotoSupply POS: the real configuration is stored outside the public web folder.\n"
                    . "defined('MOTO_ROOT') || exit;\n\nreturn require __DIR__ . '/" . addslashes($rel) . "';\n";
                if (self::atomicWrite(self::path(), $stub)) {
                    return 'private';
                }
                @unlink($file);
            }
        }
        if (!self::atomicWrite(self::path(), $content)) {
            throw new \RuntimeException('config not writable');
        }
        return 'webroot';
    }

    private static function atomicWrite(string $file, string $content): bool
    {
        $tmp = $file . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (@file_put_contents($tmp, $content, LOCK_EX) === false) {
            return false;
        }
        @chmod($tmp, 0640);
        if (!@rename($tmp, $file)) {
            @unlink($tmp);
            return false;
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($file, true);
        }
        return true;
    }
}
